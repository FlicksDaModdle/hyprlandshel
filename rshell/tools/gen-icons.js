// Writes ui/icons.slint from the shell's glyphs (shell/quickshell/modules/icons/IconPaths.js),
// so the Rust shell draws exactly the icons the QML one does.
//   node rshell/tools/gen-icons.js
const fs = require("fs"), path = require("path");
const src = fs.readFileSync(path.join(__dirname, "../../shell/quickshell/modules/icons/IconPaths.js"), "utf8")
    .replace(/^\.pragma library/m, "");
const icons = new Function(src + "\nreturn icons;")();
const kebab = s => s.replace(/[A-Z]/g, m => "-" + m.toLowerCase());
const q = s => JSON.stringify(s || "");
let out = "// Generated from shell/quickshell/modules/icons/IconPaths.js by rshell/tools/gen-icons.js:\n"
        + "// the shell's own glyphs, so the Rust shell draws exactly the same icons.\n"
        + "export struct GlyphData { ink: string, acc: string, ink-w: string, acc-w: string, fill: string, fill-ink: string, "
        + "dot-x: float, dot-y: float, dot-r: float, dot-acc: bool }\n\nexport global Icons {\n";
const seen = new Set();
for (const name of Object.keys(icons)) {
    const g = icons[name], k = kebab(name);
    if (seen.has(k)) continue;
    seen.add(k);
    const d = (g.dots && g.dots[0]) || null;
    out += `    out property <GlyphData> ${k}: { ink: ${q(g.ink)}, acc: ${q(g.acc)}, ink-w: ${q(g.inkW)}, acc-w: ${q(g.accW)}, `
         + `fill: ${q(g.fill)}, fill-ink: ${q(g.fillInk)}, dot-x: ${d ? d.cx : 0}, dot-y: ${d ? d.cy : 0}, `
         + `dot-r: ${d ? d.r : 0}, dot-acc: ${d && d.c === "acc" ? "true" : "false"} };\n`;
}
fs.writeFileSync(path.join(__dirname, "../ui/icons.slint"), out + "}\n");

// The same glyphs by name for the Rust side, for what names its icon in
// data (pinned apps, commands, files): glyph("stickyNote") or
// glyph("sticky-note").
let rs = "//! Generated by rshell/tools/gen-icons.js from the shell's glyphs: each by\n"
       + "//! name, for icons named in data (a pinned app's \"stickyNote\").\n\n"
       + "use crate::GlyphData;\n\n"
       + "pub fn glyph(name: &str) -> GlyphData {\n"
       + "    let k: String = name.chars().flat_map(|c| if c.is_ascii_uppercase() { vec!['-', c.to_ascii_lowercase()] } else { vec![c] }).collect();\n"
       + "    let g = |ink: &str, acc: &str, ink_w: &str, acc_w: &str, fill: &str, fill_ink: &str, dx: f32, dy: f32, dr: f32, da: bool| GlyphData {\n"
       + "        ink: ink.into(), acc: acc.into(), ink_w: ink_w.into(), acc_w: acc_w.into(), fill: fill.into(), fill_ink: fill_ink.into(),\n"
       + "        dot_x: dx, dot_y: dy, dot_r: dr, dot_acc: da,\n"
       + "    };\n"
       + "    match k.as_str() {\n";
const done = new Set();
for (const name of Object.keys(icons)) {
    const g = icons[name], k = kebab(name);
    if (done.has(k)) continue;
    done.add(k);
    const d = (g.dots && g.dots[0]) || null;
    const f = n => (n === undefined || n === null ? 0 : n).toFixed(3) + "f32".replace("f32", "");
    rs += `        ${q(k)} => g(${q(g.ink)}, ${q(g.acc)}, ${q(g.inkW)}, ${q(g.accW)}, ${q(g.fill)}, ${q(g.fillInk)}, `
        + `${d ? Number(d.cx).toFixed(3) : "0.0"}, ${d ? Number(d.cy).toFixed(3) : "0.0"}, ${d ? Number(d.r).toFixed(3) : "0.0"}, ${d && d.c === "acc" ? "true" : "false"}),\n`;
}
rs += "        _ => g(\"\", \"\", \"\", \"\", \"\", \"\", 12.0, 12.0, 2.0, false),\n    }\n}\n";
fs.writeFileSync(path.join(__dirname, "../src/glyphs.rs"), rs);
console.log(seen.size + " glyphs → rshell/ui/icons.slint");
